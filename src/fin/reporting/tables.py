def table1cv(v: Store) -> str:
    """Cross-validation table of the classifiers."""
    rows = []
    for m in CLS:
        if f"cv.{m}.mf1" not in v:
            continue
        dm = (
            (cell(v, f"cv.{m}.vsdfn.mf1") + r" {\footnotesize " + cell(v, f"cv.{m}.vsdfn.mf1.ci") + "}")
            if m != "deepfetalnet"
            else "--"
        )
        da = (
            (cell(v, f"cv.{m}.vsdfn.auc") + r" {\footnotesize " + cell(v, f"cv.{m}.vsdfn.auc.ci") + "}")
            if m != "deepfetalnet"
            else "--"
        )
        rows.append(
            f"{CLS_NAME[m]} & {cell(v, f'cv.{m}.mf1')} & {{\\footnotesize {cell(v, f'cv.{m}.mf1.range')}}} & "
            f"{cell(v, f'cv.{m}.auc')} & {{\\footnotesize {cell(v, f'cv.{m}.auc.range')}}} & "
            f"{cell(v, f'cv.{m}.sens')} & {cell(v, f'cv.{m}.spec')} & {cell(v, f'cv.{m}.rank.mf1')} & {dm} & {da}"
            + r" \\"
        )
    return (
        HDR
        + r"""\begin{table}[t]
\tablecaption{Standard-plane classification under patient-grouped """
        + cell(v, "cv.k")
        + r"""-fold cross-validation over all """
        + cell(v, "data.jnu.women")
        + r""" women of JNU-IFM (one training seed per fold; every frame is tested once, by the model whose training set excluded its woman). Threshold 0.5, Standard positive. Macro-F1, AUC, sensitivity and specificity are mean $\pm$ SD over folds, with the range over folds in small type (\%, AUC as a fraction). Rank: mean rank by macro-F1 among the seven models over folds (best--worst). $\Delta$: difference to DeepFetalNet on the pooled out-of-fold predictions, with a 95\% CI from a bootstrap over women ("""
        + cell(v, "cv.nboot")
        + r""" resamples).}
\label{tab:cv}
\centering\small
\resfit{%
\begin{tabular}{lrrrrrrrrr}
\hline
Model & \multicolumn{2}{c}{Macro-F1} & \multicolumn{2}{c}{AUC} & Sens. & Spec. & Rank & $\Delta$ Macro-F1 & $\Delta$ AUC \\
 & mean $\pm$ SD & range & mean $\pm$ SD & range & & & (best--worst) & [95\% CI] & [95\% CI] \\
\hline
"""
        + "\n".join(rows)
        + r"""
\hline
\end{tabular}}
\end{table}
"""
    )
