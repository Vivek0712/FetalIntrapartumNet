"""LaTeX tables of the paper (Tables 1-5, the cross-validation table and the supplementary AUC table).

Every cell is a value of the store filled by ``fin.reporting.values``; a missing value prints as ``\\res{key}`` (a red
??key in the PDF), an undefined metric of an existing run as ``--``.
"""

from __future__ import annotations

from fin.reporting.fmt import Store
from fin.reporting.names import CLS, CLS_NAME, SEG, SEG_NAME
from fin.reporting.values import CLS_METRICS
from fin.robustness.corruptions import CORRUPTION_NAME, conditions

HDR = "%% GENERATED by fin.reporting.fill_results (src/fin/reporting/fill_results.py) -- do not edit by hand.\n"


def cell(v: Store, key: str, exists: str | None = None) -> str:
    """Value of ``key``; ``--`` when the run exists but the metric is undefined; otherwise a ``\\res{key}`` marker
    (printed as a red ??key in the PDF) so a missing result stays visible."""
    if key in v:
        return v[key]
    if exists and exists in v:
        return "--"
    return r"\res{" + key + "}"


def seeds_text(v: Store) -> str:
    """'seeds 0, 1, 2 for AoP-GAU-Net and MALUNet; 0, 1 for U-Net and FAT-Net', grouped from seg.<m>.seeds."""
    groups = {}
    for m in SEG:
        groups.setdefault(cell(v, f"seg.{m}.seeds"), []).append(SEG_NAME[m])
    parts = [
        f"{sd} for {' and '.join(ns) if len(ns) < 3 else ', '.join(ns[:-1]) + ' and ' + ns[-1]}"
        for sd, ns in sorted(groups.items(), key=lambda kv: -len(kv[0]))
    ]
    return "seeds " + "; ".join(parts)


def weak_sd_text(v: Store) -> str:
    """Caveat appended to the seed list when any segmenter has fewer than three seeds."""
    counts = [len(str(v.get(f"seg.{m}.seeds", "")).split(",")) for m in SEG if v.get(f"seg.{m}.seeds", "")]
    return "; with two seeds the SD is a weak spread estimate" if counts and min(counts) < 3 else ""


def table1(v: Store) -> str:
    """Table 1: classification on the test split (mean +/- SD and seed-averaged bootstrap CI)."""
    rows = []
    for m in CLS:
        vals = [cell(v, f"cls.{m}.{k}", f"cls.{m}.nseeds") for k, *_ in CLS_METRICS]
        cis = [v.get(f"cls.{m}.{k}.ci", "") for k, *_ in CLS_METRICS]
        rows.append(f"{CLS_NAME[m]} & " + " & ".join(vals) + r" \\")
        if any(cis):
            rows.append(
                r"\multicolumn{1}{r}{\footnotesize 95\% CI} & "
                + " & ".join(r"{\footnotesize " + c + "}" for c in cis)
                + r" \\[2pt]"
            )
    return (
        HDR
        + r"""\begin{table}[t]
\tablecaption{Standard-plane classification on the JNU-IFM test split ("""
        + cell(v, "cls.ntest")
        + r""" frames from """
        + cell(v, "data.split.test.videos")
        + r""" videos of """
        + cell(v, "data.split.test.women")
        + r""" women; """
        + cell(v, "cls.ntest.standard")
        + r""" Standard, """
        + cell(v, "cls.ntest.nonstandard")
        + r""" Non-Standard). Standard (SPHead) is the positive class and the decision threshold is 0.5. Values are mean $\pm$ SD over training seeds """
        + cell(v, "cls.seeds")
        + r"""; the second line of each row is the 95\% confidence interval of the seed-averaged metric from a cluster bootstrap over test videos ("""
        + cell(v, "cls.nboot")
        + r""" resamples). Accuracy, precision, sensitivity and specificity in \%; F1-score, macro-F1 and ROC-AUC as fractions (0--1).}
\label{tab:cls}
\centering\small
\resfit{%
\begin{tabular}{lrrrrrrr}
\hline
Model & Accuracy & Precision & Sensitivity & Specificity & F1-score & Macro-F1 & ROC-AUC \\
\hline
"""
        + "\n".join(rows)
        + r"""
\hline
\end{tabular}}
\end{table}
"""
    )


