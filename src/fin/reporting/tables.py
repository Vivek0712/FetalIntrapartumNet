def table3(v: Store) -> str:
    """Table 3: robustness of DeepFetalNet and the best baseline by validation AUC."""
    base = v.get("cls.baseline.valbest.id")
    models = ["deepfetalnet"] + ([base] if base else [])
    head_names = " & ".join(r"\multicolumn{4}{c}{" + (CLS_NAME[m]) + "}" for m in models)
    rows, last = [], None
    for cid, kind, _, label in conditions():
        name = CORRUPTION_NAME[kind] if kind != last else ""
        last = kind
        cells = []
        for m in models:
            cells += [cell(v, f"rob.{m}.{cid}.{k}", f"rob.{m}.nseeds") for k in ("acc", "sens", "spec", "auc")]
        rows.append(f"{name} & {label if kind != 'none' else '--'} & " + " & ".join(cells) + r" \\")
    cm = " ".join(r"\cline{" + f"{3 + 4 * i}-{6 + 4 * i}" + "}" for i in range(len(models)))
    basetxt = (r" and of the baseline with the highest mean validation AUC (" + CLS_NAME[base] + ")") if base else ""
    return (
        HDR
        + r"""\begin{table}[t]
\tablecaption{Classification robustness on the corrupted JNU-IFM test split ("""
        + cell(v, "rob.nframes")
        + r""" frames; Standard positive; threshold 0.5) for DeepFetalNet"""
        + basetxt
        + r""". Each corruption is applied to the $224 \times 224$ input in $[0, 1]$ before normalisation, with a fixed random seed per frame, so all models see identical pixels (definitions in Section~\ref{sec:metrics}). Mean $\pm$ SD over training seeds; accuracy, sensitivity and specificity in \%. The AUC of all seven classifiers under every condition is given in the supplementary material.}
\label{tab:robust}
\centering\small
\resfit{%
\begin{tabular}{ll"""
        + "rrrr" * len(models)
        + r"""}
\hline
 & & """
        + head_names
        + r""" \\
"""
        + cm
        + r"""
Corruption & Setting"""
        + (r" & Acc. & Sens. & Spec. & AUC" * len(models))
        + r""" \\
\hline
"""
        + "\n".join(rows)
        + r"""
\hline
\end{tabular}}
\end{table}
"""
    )


